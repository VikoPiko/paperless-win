#Requires -Version 7
<#
.SYNOPSIS
  Soak test for the consume folder: drop N mixed files in bursts, some written slowly
  while exclusively locked, and assert that every one is consumed exactly once.

.DESCRIPTION
  Assumes the stack is running (Garnet, web, worker(s), consumer) and these are set:
    PAPERLESS_URL, PAPERLESS_USER, PAPERLESS_PASS
  Pass the consume folder with -ConsumeDir (a local folder or an SMB share; for a share the
  consumer must run in polling mode, which paperless-win enables by default for UNC paths).

  Files are generated by make_soak_files.py with a unique random token each. Afterwards the
  script checks, through the REST API, that:
    * every token appears in exactly one document (nothing lost, no duplicates),
    * the consume folder is empty again,
    * no consume task for this run failed.
  The documents it created are deleted afterwards unless -Keep is given.

  Exit code 0 = passed, 1 = a check failed, 2 = bad setup.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string]$ConsumeDir,
    [int]$Count = 200,
    [int]$BurstSize = 20,
    [int]$BurstPauseSeconds = 4,
    [int]$SlowWriters = 12,          # of the files, how many are written slowly under an exclusive lock
    [int]$TimeoutMinutes = 40,
    [string]$Python = '',
    [switch]$Keep
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$repo = (Resolve-Path "$PSScriptRoot\..\..").Path
if (-not $Python) { $Python = Join-Path $repo '.venv\Scripts\python.exe' }
foreach ($name in 'PAPERLESS_URL', 'PAPERLESS_USER', 'PAPERLESS_PASS') {
    if (-not (Get-Item "Env:$name" -ErrorAction SilentlyContinue)) { Write-Error "$name is not set"; exit 2 }
}
if (-not (Test-Path $ConsumeDir)) { Write-Error "consume dir not found: $ConsumeDir"; exit 2 }
if (-not (Test-Path $Python)) { Write-Error "python not found: $Python"; exit 2 }

$base = $env:PAPERLESS_URL.TrimEnd('/')
$basic = [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes("$($env:PAPERLESS_USER):$($env:PAPERLESS_PASS)"))
$headers = @{ Authorization = "Basic $basic"; Accept = 'application/json; version=9' }

$runId = [guid]::NewGuid().ToString('N').Substring(0, 6)
$stage = Join-Path ([IO.Path]::GetTempPath()) "paperless-soak-$runId"
$seed = [int]([datetime]::UtcNow.Ticks % 100000)
& $Python (Join-Path $PSScriptRoot 'make_soak_files.py') $stage --count $Count --seed $seed | Out-Host
$manifest = Get-Content (Join-Path $stage 'manifest.json') -Raw | ConvertFrom-Json
$files = @($manifest.files)
Write-Host "Run $runId : $($files.Count) files ($(($files | Group-Object kind | ForEach-Object { "$($_.Count) $($_.Name)" }) -join ', ')) -> $ConsumeDir"
$before = @(Get-ChildItem $ConsumeDir -File -ErrorAction SilentlyContinue).Count

# --- drop the files -----------------------------------------------------------------------------
$slow = $files | Select-Object -Last $SlowWriters
$fast = $files | Select-Object -First ($files.Count - $SlowWriters)
$started = Get-Date

# Slow writers: exclusive lock, 8 chunks, 250 ms apart (like a scanner or a network copy)
$slowJobs = foreach ($f in $slow) {
    Start-ThreadJob -ArgumentList $stage, $ConsumeDir, $f.name -ScriptBlock {
        param($stage, $dest, $name)
        $bytes = [IO.File]::ReadAllBytes((Join-Path $stage $name))
        $stream = [IO.File]::Open((Join-Path $dest $name), [IO.FileMode]::Create, [IO.FileAccess]::Write, [IO.FileShare]::None)
        try {
            $chunk = [Math]::Max([int][Math]::Ceiling($bytes.Length / 8), 1)
            for ($i = 0; $i -lt $bytes.Length; $i += $chunk) {
                $stream.Write($bytes, $i, [Math]::Min($chunk, $bytes.Length - $i))
                $stream.Flush()
                Start-Sleep -Milliseconds 250
            }
        }
        finally { $stream.Dispose() }
    }
}

$n = 0
foreach ($f in $fast) {
    Copy-Item (Join-Path $stage $f.name) (Join-Path $ConsumeDir $f.name)
    $n++
    if ($n % $BurstSize -eq 0) { Start-Sleep -Seconds $BurstPauseSeconds }
}
$slowJobs | Wait-Job | Receive-Job | Out-Null
Write-Host ("All files dropped after {0:N0} s; waiting for the consume folder to empty" -f ((Get-Date) - $started).TotalSeconds)

# --- wait for the consume folder to drain ---------------------------------------------------------
$deadline = (Get-Date).AddMinutes($TimeoutMinutes)
$names = $files.name
do {
    Start-Sleep -Seconds 10
    $left = @(Get-ChildItem $ConsumeDir -File -ErrorAction SilentlyContinue | Where-Object { $names -contains $_.Name })
    Write-Host ("  {0} file(s) left in the consume folder" -f $left.Count)
} while ($left.Count -gt 0 -and (Get-Date) -lt $deadline)

# Give the last documents time to be indexed
Start-Sleep -Seconds 15

# --- verify ---------------------------------------------------------------------------------------
$failures = [System.Collections.Generic.List[string]]::new()
function Assert-That([bool]$Condition, [string]$Message) {
    if ($Condition) { Write-Host "  PASS  $Message" -ForegroundColor Green }
    else { Write-Host "  FAIL  $Message" -ForegroundColor Red; $script:failures.Add($Message) }
}

$stillThere = @(Get-ChildItem $ConsumeDir -File -ErrorAction SilentlyContinue | Where-Object { $names -contains $_.Name })
Assert-That ($stillThere.Count -eq 0) "consume folder holds none of this run's files ($($stillThere.Count) left: $(($stillThere.Name | Select-Object -First 5) -join ', '))"

$docIds = [System.Collections.Generic.List[int]]::new()
$missing = @(); $dupes = @(); $badText = @(); $ocrMisses = @()
foreach ($f in $files) {
    # Identity is the original file name (unique per file). The token is the content check.
    $res = Invoke-RestMethod "$base/api/documents/?original_filename__iexact=$([uri]::EscapeDataString($f.name))&fields=id,content" -Headers $headers
    $hits = @($res.results)
    if ($hits.Count -eq 0) { $missing += $f.name; continue }
    if ($hits.Count -gt 1) { $dupes += "$($f.name) x$($hits.Count)" }
    $hits | ForEach-Object { $docIds.Add([int]$_.id) }
    $hasToken = ("$($hits[0].content)" -match $f.token)
    if (-not $hasToken) {
        if ($f.kind -eq 'txt') { $badText += $f.name } else { $ocrMisses += $f.name }
    }
}
Assert-That ($missing.Count -eq 0) "every file became a document ($($files.Count - $missing.Count)/$($files.Count); missing: $(($missing | Select-Object -First 5) -join '; '))"
Assert-That ($dupes.Count -eq 0) "no file became more than one document (duplicates: $(($dupes | Select-Object -First 5) -join '; '))"
Assert-That ($badText.Count -eq 0) "text files kept their exact content ($($badText.Count) differ: $(($badText | Select-Object -First 5) -join '; '))"
if ($ocrMisses.Count -gt 0) {
    Write-Host "  note  OCR did not reproduce the random token for $($ocrMisses.Count) image file(s): $(($ocrMisses | Select-Object -First 5) -join ', ') (an OCR accuracy matter, not a consume failure)" -ForegroundColor Yellow
}
$tasks = @(Invoke-RestMethod "$base/api/tasks/" -Headers $headers)
$failedTasks = @($tasks | Where-Object { $_.status -eq 'FAILURE' -and $_.task_file_name -and $names -contains $_.task_file_name })
Assert-That ($failedTasks.Count -eq 0) "no consume task failed ($($failedTasks.Count); first: $(($failedTasks | Select-Object -First 1).result))"

if (-not $Keep) {
    foreach ($id in ($docIds | Select-Object -Unique)) { Invoke-RestMethod "$base/api/documents/$id/" -Method Delete -Headers $headers | Out-Null }
    Write-Host "  (deleted $(@($docIds | Select-Object -Unique).Count) documents)"
}
Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue

if ($failures.Count -gt 0) {
    Write-Host "Soak test FAILED: $($failures.Count) check(s)" -ForegroundColor Red
    exit 1
}
Write-Host ("Soak test passed: {0} files in {1:N1} min" -f $files.Count, ((Get-Date) - $started).TotalMinutes) -ForegroundColor Green
exit 0
